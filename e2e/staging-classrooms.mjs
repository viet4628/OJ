// Real browser flow against the configured staging DB; only disposable fixtures.
import fs from 'node:fs';
import { mkdir } from 'node:fs/promises';
import { randomBytes } from 'node:crypto';
import { chromium } from 'playwright';
import { createClient } from '../apps/judge-worker/node_modules/@supabase/supabase-js/dist/index.mjs';
import dotenv from '../apps/judge-worker/node_modules/dotenv/lib/main.js';
import assert from 'node:assert/strict';
const env = dotenv.parse(fs.readFileSync(new URL('../.env', import.meta.url)));
const db = createClient(env.SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false, autoRefreshToken: false } });
const web = process.env.STAGING_WEB_URL || 'http://127.0.0.1:3000';
const suffix = randomBytes(4).toString('hex');
const name = `Lớp thử nghiệm ${suffix}`;
const code = `CL${suffix.toUpperCase()}`;
const users = [];
const clients = [];
const frontend = dotenv.parse(fs.readFileSync(new URL('../apps/web/.env.local', import.meta.url)));
let problemId;
let browser;
const must = ({ data, error }) => { if (error) throw new Error(error.message); return data; };
async function login(page, account) {
  await page.goto(web + '/');
  await page.getByRole('button', { name: /đăng nhập/i }).first().click();
  const dialog = page.getByRole('dialog');
  await dialog.locator('input[type=email]').fill(account.email);
  await dialog.locator('input[type=password]').fill(account.password);
  await dialog.getByRole('button', { name: 'Đăng Nhập', exact: true }).click();
  await dialog.waitFor({ state: 'hidden', timeout: 30000 });
}
try {
  for (const role of ['teacher', 'user', 'outsider']) {
    const email = `classroom-${role}-${suffix}@example.invalid`;
    const password = randomBytes(20).toString('base64url');
    const { user } = must(await db.auth.admin.createUser({ email, password, email_confirm: true, user_metadata: { full_name: `Classroom fixture ${role}` } }));
    users.push({ id: user.id, email, password });
    if (role === 'teacher') must(await db.from('profiles').update({ role }).eq('id', user.id));
  }
  must(await db.from('classrooms').insert({ name: 'Existing fixture code', code, teacher_id: users[0].id }));
  const problem = must(await db.from('problems').insert({ slug: `classroom-${suffix}`, title: `Bài tập đầu tiên ${suffix}`, description: 'Disposable classroom fixture', is_public: false, created_by: users[0].id }).select('id,title').single());
  problemId = problem.id;
  must(await db.from('testcases').insert({ problem_id: problem.id, input_path: 'inline', output_path: 'inline', input_content: '', output_content: '42', score: 100 }));
  browser = await chromium.launch({ headless: true });
  const teacherContext = await browser.newContext({ permissions: ['clipboard-read', 'clipboard-write'] });
  const teacher = await teacherContext.newPage();
  const errors = [];
  teacher.on('pageerror', error => errors.push(error.message));
  await login(teacher, users[0]);
  await teacher.goto(web + '/teacher');
  await teacher.getByRole('button', { name: 'Tạo Lớp Học Mới', exact: true }).click();
  const form = teacher.getByRole('dialog', { name: 'Tạo lớp học mới', exact: true });
  await form.getByLabel('Tên lớp học').fill('  ' + name + '  ');
  await form.getByLabel('Mô tả lớp').fill('Luyện lập trình theo nhóm');
  await form.getByLabel('Mã mời').fill(code.toLowerCase());
  await form.getByRole('button', { name: 'Tạo lớp học', exact: true }).click();
  await form.getByRole('alert').filter({ hasText: 'Mã mời này đã được sử dụng' }).waitFor();
  assert.equal(await form.getByLabel('Tên lớp học').inputValue(), '  ' + name + '  ');
  console.log('PASS staging: duplicate code has clear error and preserves draft');
  await form.getByLabel('Mã mời').fill('');
  await form.getByRole('button', { name: 'Tạo lớp học', exact: true }).click();
  await teacher.getByRole('heading', { name, exact: true }).waitFor();
  const classroom = must(await db.from('classrooms').select('*').eq('teacher_id', users[0].id).eq('name', name).single());
  assert.match(classroom.code, /^[A-Z0-9]{6}$/);
  await teacher.getByRole('button', { name: 'Sao chép mã lớp', exact: true }).click();
  assert.equal(await teacher.evaluate(() => navigator.clipboard.readText()), classroom.code);
  await mkdir(new URL('test-results/', import.meta.url), { recursive: true });
  console.log('PASS staging: class saved, detail opens automatically, invite code copied');
  await teacher.getByRole('button', { name: 'Giao bài tập ngay', exact: true }).click();
  const picker = teacher.getByRole('dialog', { name: 'Giao Bài Tập Cho Lớp Học' });
  await picker.getByLabel('Chọn bài tập từ ngân hàng đề').fill(suffix);
  await picker.getByRole('button', { name: new RegExp(problem.title) }).click();
  await picker.getByLabel('Hạn chót nộp bài').fill('2000-01-01T10:00');
  await picker.getByRole('button', { name: 'Xác Nhận Thêm' }).click();
  await picker.getByRole('alert').filter({ hasText: 'Hạn nộp cần nằm trong tương lai' }).waitFor();
  await picker.getByLabel('Hạn chót nộp bài').fill('');
  await picker.getByRole('button', { name: 'Xác Nhận Thêm' }).click();
  await picker.waitFor({ state: 'hidden' });
  await teacher.getByRole('cell', { name: new RegExp(problem.title) }).waitFor();
  console.log('PASS staging: assignment deadline validated and first private problem assigned');
  const studentContext = await browser.newContext();
  const student = await studentContext.newPage();
  student.on('pageerror', error => errors.push(error.message));
  await login(student, users[1]);
  await student.goto(web + '/classes');
  await student.getByRole('button', { name: /Tham Gia Lớp|Nhập Mã Tham Gia Lớp/i }).first().click();
  await student.getByPlaceholder('Ví dụ: TIN11A').fill(classroom.code);
  await student.getByRole('button', { name: 'Vào Lớp Ngay', exact: true }).click();
  await student.waitForURL(web + '/classes/' + classroom.id);
  await student.getByRole('heading', { name, exact: true }).waitFor();
  await student.getByText(problem.title, { exact: true }).waitFor();
  const members = must(await db.from('classroom_members').select('user_id').eq('classroom_id', classroom.id));
  assert.deepEqual(members.map(row => row.user_id), [users[1].id]);
  console.log('PASS staging: student joins using invite code and sees assigned private problem');
  const studentApi = createClient(env.SUPABASE_URL, env.SUPABASE_ANON_KEY || frontend.VITE_SUPABASE_ANON_KEY, { auth: { persistSession: false, autoRefreshToken: false } });
  const outsiderApi = createClient(env.SUPABASE_URL, env.SUPABASE_ANON_KEY || frontend.VITE_SUPABASE_ANON_KEY, { auth: { persistSession: false, autoRefreshToken: false } });
  clients.push(studentApi, outsiderApi);
  must(await studentApi.auth.signInWithPassword({ email: users[1].email, password: users[1].password }));
  must(await outsiderApi.auth.signInWithPassword({ email: users[2].email, password: users[2].password }));
  const submission = { user_id: users[1].id, problem_id: problem.id, classroom_id: classroom.id, language: 'cpp', code: '#include <cstdio>\nint main(){printf("42");}' };
  const { id: submissionId } = must(await studentApi.from('submissions').insert(submission).select('id').single());
  let result;
  const deadline = Date.now() + 90000;
  do {
    result = must(await studentApi.from('submissions').select('status,score,classroom_id').eq('id', submissionId).single());
    if (!['PENDING','JUDGING'].includes(result.status)) break;
    await new Promise(resolve => setTimeout(resolve, 500));
  } while (Date.now() < deadline);
  assert.equal(result.status, 'ACCEPTED'); assert.equal(result.score, 100); assert.equal(result.classroom_id, classroom.id);
  const progress = must(await studentApi.rpc('get_classroom_progress', { p_classroom_id: classroom.id }));
  assert.equal(progress.length, 1); assert.equal(progress[0].score, 100);
  must(await db.from('classroom_problems').update({ deadline: new Date(Date.now()-1).toISOString() }).eq('classroom_id', classroom.id).eq('problem_id', problem.id));
  assert((await studentApi.from('submissions').insert(submission)).error, 'Late class submission accepted');
  assert((await outsiderApi.from('submissions').insert({ ...submission, user_id: users[2].id })).error, 'Outsider class submission accepted');
  assert((await outsiderApi.rpc('get_classroom_progress', { p_classroom_id: classroom.id })).error, 'Outsider can read class grades');
  console.log('PASS staging: class submission AC/100 through deployed engine, grade RPC, expired deadline and outsider guards');

  await teacher.goto(web + '/teacher');
  await teacher.getByRole('heading', { name, exact: true }).click();
  await teacher.getByRole('cell', { name: new RegExp(problem.title) }).waitFor();
  await teacher.getByRole('button', { name: /Học Sinh \(1\)/ }).waitFor();
  await teacher.screenshot({ path: new URL('test-results/classroom-created.png', import.meta.url).pathname, fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS staging: teacher sees one student after reload; no browser exceptions');
  await teacher.goto(web + '/teacher');
  await teacher.setViewportSize({ width: 390, height: 844 });
  await teacher.getByRole('button', { name: 'Tạo Lớp Học Mới', exact: true }).click();
  await teacher.getByRole('dialog', { name: 'Tạo lớp học mới' }).waitFor();
  assert(await teacher.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile viewport overflows');
  await teacher.screenshot({ path: new URL('test-results/classroom-create-mobile.png', import.meta.url).pathname, fullPage: true });
  console.log('PASS staging: create form fits mobile viewport');
} finally {
  await browser?.close();
  for (const client of clients) await client.auth.signOut().catch(() => {});
  if (users[0]) must(await db.from('classrooms').delete().eq('teacher_id', users[0].id));
  if (problemId) must(await db.from('problems').delete().eq('id', problemId));
  for (const user of users.reverse()) must(await db.auth.admin.deleteUser(user.id));
  console.log('Temporary classroom/problem/accounts cleaned up');
}
